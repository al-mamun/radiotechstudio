    function get(key) {
    const parts = key.split('.');
    let val = t[current];
    for (const p of parts) { val = val && val[p]; }
    if (val === undefined) {
      val = t[DEFAULT];
      for (const p of parts) { val = val && val[p]; }
    }
    return val !== undefined ? val : key;
  }

  function applyAll() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const v = get(el.dataset.i18n);
      if (v) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const v = get(el.dataset.i18nPh);
      if (v) el.placeholder = v;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const v = get(el.dataset.i18nAria);
      if (v) el.setAttribute('aria-label', v);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const v = get(el.dataset.i18nTitle);
      if (v) el.setAttribute('title', v);
    });
    // Page title
    const titleVal = get('meta.title');
    if (titleVal) document.title = titleVal;
  }

  function updateSwitcherUI(lang) {
    const flags = { en: '🇬🇧', ar: '🇸🇦', fr: '🇫🇷', es: '🇪🇸', de: '🇩🇪' };
    const codes = { en: 'EN', ar: 'AR', fr: 'FR', es: 'ES', de: 'DE' };
    const flagEl = document.querySelector('.lang-flag');
    const codeEl = document.querySelector('.lang-code');
    if (flagEl) flagEl.textContent = flags[lang] || '🌐';
    if (codeEl) codeEl.textContent = codes[lang] || lang.toUpperCase();
    document.querySelectorAll('.lang-option').forEach(opt => {
      opt.setAttribute('aria-selected', opt.dataset.lang === lang ? 'true' : 'false');
      opt.classList.toggle('lang-option--active', opt.dataset.lang === lang);
    });
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang)) return;
    current = lang;
    const html = document.documentElement;
    html.lang = lang;
    html.dir = RTL.includes(lang) ? 'rtl' : 'ltr';
    html.classList.toggle('is-rtl', RTL.includes(lang));
    applyAll();
    updateSwitcherUI(lang);
    try { localStorage.setItem('rts_lang', lang); } catch (_) {}
    document.dispatchEvent(new CustomEvent('rts:langChange', { detail: { lang } }));
  }

  function initSwitcher() {
    const toggle = document.querySelector('.lang-toggle');
    const dropdown = document.getElementById('lang-dropdown');
    if (!toggle || !dropdown) return;

    toggle.addEventListener('click', () => {
      const open = toggle.getAttribute('aria-expanded') === 'true';
      toggle.setAttribute('aria-expanded', String(!open));
      dropdown.hidden = open;
      if (!open) {
        const active = dropdown.querySelector('.lang-option--active, .lang-option');
        if (active) active.focus();
      }
    });

    dropdown.addEventListener('click', e => {
      const opt = e.target.closest('.lang-option');
      if (!opt) return;
      setLang(opt.dataset.lang);
      toggle.setAttribute('aria-expanded', 'false');
      dropdown.hidden = true;
      toggle.focus();
    });

    dropdown.addEventListener('keydown', e => {
      const opts = [...dropdown.querySelectorAll('.lang-option')];
      const idx  = opts.indexOf(document.activeElement);
      if (e.key === 'ArrowDown') { e.preventDefault(); opts[(idx + 1) % opts.length].focus(); }
      if (e.key === 'ArrowUp')   { e.preventDefault(); opts[(idx - 1 + opts.length) % opts.length].focus(); }
      if (e.key === 'Escape')    { toggle.setAttribute('aria-expanded','false'); dropdown.hidden = true; toggle.focus(); }
    });

    document.addEventListener('click', e => {
      if (!e.target.closest('.lang-switcher')) {
        toggle.setAttribute('aria-expanded', 'false');
        dropdown.hidden = true;
      }
    });
  }

  function init() {
    let lang = DEFAULT;
    try { lang = localStorage.getItem('rts_lang') || DEFAULT; } catch (_) {}
    if (!SUPPORTED.includes(lang)) {
      const b = (navigator.language || '').split('-')[0];
      lang = SUPPORTED.includes(b) ? b : DEFAULT;
    }
    setLang(lang);
    initSwitcher();
  }

  return { init, setLang, get };

